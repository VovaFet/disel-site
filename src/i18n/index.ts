// "13 жовтня 2026" from YYYY-MM-DD (as UTC, so the day never shifts)
export const formatDate = (lang: Locale, date: string) =>
  new Date(`${date}T00:00:00Z`).toLocaleDateString(lang === "en" ? "en-GB" : lang === "ru" ? "ru-RU" : "uk-UA", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  });

